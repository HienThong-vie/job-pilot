export function OAuthButton({ provider, label }: Props) {
  const isGoogle = provider === "google";

  return (
    <form
      action={signInWithOAuthAction.bind(null, provider)}
      onSubmit={() => posthog.capture("sign_in_started", { provider })}
    >
      <SubmitButton
        className={
          isGoogle
            ? "flex h-11 w-full items-center justify-center gap-3 rounded-md border border-border bg-surface text-sm font-medium text-text-primary"
            : "flex h-11 w-full items-center justify-center gap-3 rounded-md bg-accent text-sm font-medium text-accent-foreground"
        }
      >
        {isGoogle ? <GoogleIcon /> : <GithubIcon />}
        {label}
      </SubmitButton>
    </form>
  );
}
